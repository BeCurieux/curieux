/**
 * Activity taxonomy (§9 screens 6 and 7).
 *
 * Kept extensible: a category is a row here, not a union baked into fifty
 * switch statements. Each carries the properties the hard filters and scorers
 * actually need — whether it is weather-proof, how exposed it is, how much it
 * typically costs, which child ages it works for — so adding "wildlife park"
 * later means adding one entry, not editing the planner.
 */

export type CategoryId = string;

export interface Category {
  id: CategoryId;
  /** Customer-facing label. Sentence case; these appear on chips. */
  label: string;
  /** Grouping for the onboarding grid. */
  group: "outdoors" | "food" | "culture" | "active" | "family" | "explore";
  /** Usable in rain without a miserable experience. */
  weatherproof: boolean;
  /** 0 = fully sheltered, 1 = fully exposed to sun and wind. */
  exposure: number;
  /** Typical spend band per adult; 0 = free. Used before we have real prices. */
  typical_cost_band: 0 | 1 | 2 | 3;
  /** Physical demand of the category itself, before distance is considered. */
  intensity: "GENTLE" | "EASY" | "MODERATE" | "ACTIVE";
  /** Minimum child age in years this is generally suitable for. 0 = any age. */
  min_child_age: number;
  /** Categories that can anchor a plan rather than merely accompany one. */
  can_anchor: boolean;
  /** Tends to be busy. Cross-referenced with crowd tolerance. */
  typically_busy: boolean;
  /** Search phrasing hints handed to the intent generator (§14). */
  search_hints: readonly string[];
}

