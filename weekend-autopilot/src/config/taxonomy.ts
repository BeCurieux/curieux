const BY_ID = new Map(CATEGORIES.map((c) => [c.id, c]));

export function category(id: CategoryId): Category | undefined {
  return BY_ID.get(id);
}

export function categoriesInGroup(group: Category["group"]): Category[] {
  return CATEGORIES.filter((c) => c.group === group);
}

export function anchorCategories(): Category[] {
  return CATEGORIES.filter((c) => c.can_anchor);
}

