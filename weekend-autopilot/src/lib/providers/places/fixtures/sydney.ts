/**
 * Synthetic Sydney place fixtures.
 *
 * This is a DEV AND TEST dataset, not a mirror of any provider's database and
 * not a source of truth about real businesses. Coordinates are approximate and
 * opening hours are invented. It exists so that the planner, the filters, the
 * verifier and the eval suite can be exercised deterministically and offline,
 * with no paid provider calls in CI (§48).
 *
 * It is deliberately broad rather than deep: enough beaches, walks, galleries,
 * pools, markets, bakeries and restaurants across enough of the city that a
 * family in Marrickville and a couple in Manly get genuinely different plans.
 */

import type { CategoryId } from "@/config/taxonomy";
import type { OpeningHours } from "@/lib/types";

export interface FixturePlace {
  id: string;
  name: string;
  lat: number;
  lng: number;
  categories: CategoryId[];
  price_level: number | null;
  rating: number;
  user_ratings_total: number;
  /** Free-form keywords the mock search matches against. */
  keywords: string[];
  /** Always-open public space (beach, park, foreshore) — verified differently. */
  public_space: boolean;
  /** Hours for commercial venues. Omitted for public spaces. */
  hours?: OpeningHours;
  /** 0–1 crowd proxy, hand-set so crowd-tolerance tests are meaningful. */
  busyness: number;
  /** Typical spend per adult, used by the mock price endpoint. */
  price_hint?: { min: number; max: number };
  address: string;
  /** Set for the small number of venues that genuinely need booking. */
  booking_required?: boolean;
  website?: string;
}

/** Weekend-ish hours helper: same window Saturday and Sunday, plus weekdays. */
function hours(open: string, close: string, days: number[] = [1, 2, 3, 4, 5, 6, 7]): OpeningHours {
  const periods: OpeningHours["periods"] = {};
  for (const day of days) periods[day] = [{ open, close }];
  return { periods, permanently_closed: false, unknown: false };
}

/** For venues whose hours the provider genuinely does not know. */
const UNKNOWN_HOURS: OpeningHours = { periods: {}, permanently_closed: false, unknown: true };

