// "How do I remember what my kids actually said?"
//
// The first entry, and the shape the rest should follow: it answers the
// question in the first paragraph, it is useful to somebody who never buys
// anything, and it mentions the product once, at the end, as the thing that
// does this for you rather than as the reason the page exists.
//
// Nothing here is a statistic. There is no research finding, no percentage
// and no claim about how memory works that a reader could check and find
// invented — the argument does not need one, and tests/journal.test.ts
// refuses them. What it does instead is describe a thing every parent
// recognises, which is stronger anyway.

export function WordsGoFirst() {
  return (
    <>
      <p>
        Write down the exact words. Not a description of what they said &mdash;
        the words, with the mistakes in. That is the whole answer, and the rest
        of this is why it is harder than it sounds and what to do about it.
      </p>

      <h2>The photographs look after themselves</h2>
      <p>
        Nobody needs advice about taking photographs of a small child. You have
        thousands. The year they were two is a folder of four thousand files,
        and you will still have it in twenty years without doing anything at
        all.
      </p>
      <p>
        What is not in that folder is everything around it. What the rabbit was
        called. Why they would only sleep with the light on. The word they said
        wrong for eight months and then, one Tuesday, said correctly &mdash;
        and you noticed, and thought <em>I must remember that</em>, and did
        not.
      </p>
      <p>
        None of it is recoverable later. A photograph of a child holding a
        rabbit does not tell you the rabbit&rsquo;s name, and no amount of
        looking at it will bring the name back. You can photograph a
        six-year-old whenever you like; you cannot go back and record what a
        three-year-old called things.
      </p>

      <h2>Exactly how they said it</h2>
      <p>
        The single most useful habit is writing quotes verbatim. Not
        &ldquo;she asked for water&rdquo; but whatever she actually said, in
        whatever order she said it, with the wrong words left wrong.
      </p>
      <p>
        The mistakes are the part you will miss. A tidied-up quote is a
        sentence any child could have said. An untidy one is unmistakably
        yours, and it is the thing that will make somebody cry in fifteen
        years&rsquo; time. Tidying is the instinct to resist &mdash; it feels
        like making the record better and it is the one edit that removes the
        person from it.
      </p>

      <h2>Four things worth writing down</h2>
      <p>
        Not a system. Four kinds of thing that are gone within a year and take
        a sentence each.
      </p>
      <ul>
        <li>
          <strong>Names for things.</strong> What they call the car, the
          bath, their sibling, the specific blanket. These change every few
          months and leave no trace.
        </li>
        <li>
          <strong>The current obsession.</strong> The one book, the one song,
          the thing that has to happen in the right order or the day is
          ruined. You think it is permanent. It lasts about a season.
        </li>
        <li>
          <strong>What ended.</strong> Harder, and worth more than the rest.
          Things stop &mdash; a comfort object, a phrase, a way of sleeping
          &mdash; and because there is no last-time ceremony you never notice
          the last time. If you spot that something has gone, write down that
          it has gone.
        </li>
        <li>
          <strong>The ordinary Tuesday.</strong> Birthdays photograph
          themselves. What disappears completely is what the middle of an
          unremarkable week actually looked like, which is where nearly all
          of a childhood happens.
        </li>
      </ul>

      <h2>A sentence is plenty</h2>
      <p>
        The reason people stop doing this is that they try to write well. A
        journal entry is a project; a line in a note is nothing. Write the
        line. &ldquo;Bun Bun tired now. Bun Bun go bed.&rdquo; is a complete
        and perfect record, and it took eleven seconds.
      </p>
      <p>
        It also does not matter where. A note on your phone, a message to
        yourself, the back of an envelope. The failure mode is not the wrong
        format, it is the sentence never being written at all &mdash; and
        anything you can do one-handed at 6am beats a system you will abandon
        in March.
      </p>

      <h2>What we do about it</h2>
      <p>
        This is more or less what Qotidia exists for. It keeps the
        photographs, and then it asks you the handful of things a photograph
        cannot answer &mdash; what that was called, whether that thing that
        keeps appearing meant something, whether the one that stopped in
        March stopped for a reason. Once a year it turns the answers and the
        photographs into a book you can put on a shelf.
      </p>
      <p>
        It does not write your family&rsquo;s memories for you, and it will
        not put words in your child&rsquo;s mouth. That is the point of it:
        the words have to be yours, because you are the only person who has
        them.
      </p>
    </>
  );
}
