/**
 * Booting a real browser over a real shop.
 *
 * The vitest suite runs in jsdom, which has no layout engine: nothing in it can
 * observe an `aspect-ratio` resolving against a container width, a grid
 * collapsing to one column, or a label rendering white on white. Those are the
 * regressions this file exists to make catchable, and catching them needs a
 * browser that actually lays the page out.
 *
 * The shop under test is built by the real pipeline — ingest the fixture
 * storefront, merchandise it, save it through the same store the route reads —
 * so an assertion here is about the renderer rather than about a hand-written
 * config shaped to pass.
 */

